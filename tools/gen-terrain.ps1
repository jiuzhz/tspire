# Generate the tower terrain functions from tools/geometry.json.
#
# Everything that has to agree with the node positions lives here:
#   map/clear_floor, map/build_hall, map/room_shell, map/room_boss,
#   map/seal_doors, map/unseal_doors, terrain/lock, terrain/unlock
#
# Why a generator: the earlier hand-written versions drifted from
# tools/gen-maps.ps1 (doors at +-7 while the walls had moved to +-8, a barrier
# ceiling over the whole hall instead of per room, /fill calls over the 32768
# block limit ...). Numbers now come from one file.
#
# NOTE: keep this file pure ASCII (PS 5.1 reads BOM-less .ps1 as ANSI).
# NOTE: command arguments use SINGLE spaces only.

$ErrorActionPreference = 'Stop'

$root   = Split-Path -Parent $PSScriptRoot
$resDir = Join-Path $root 'src\main\resources'
$mapDir = Join-Path $resDir 'data\tspire\functions\map'
$terDir = Join-Path $resDir 'data\tspire\functions\terrain'

$G = Get-Content (Join-Path $PSScriptRoot 'geometry.json') -Raw -Encoding UTF8 | ConvertFrom-Json

$rows      = [int]$G.rows
$rowSpacing= [int]$G.rowSpacing
$colSpacing= [int]$G.colSpacing
$roomHalf  = [int]$G.roomHalf
$roomWall  = [int]$G.roomWall
$roomH     = [int]$G.roomHeight
$barrierY  = [int]$G.barrierY
# v0.6.25: visible block used for PERMANENT door seals (geometry.json sealBlock).
$sealBlock = [string]$G.sealBlock
if ([string]::IsNullOrWhiteSpace($sealBlock)) { $sealBlock = 'minecraft:polished_blackstone_bricks' }
$bossHalf  = [int]$G.bossHalf
$bossWall  = [int]$G.bossWall
$bossGap   = [int]$G.bossGap
$maxCols   = [int]$G.maxCols
$cInset    = [int]$G.corridorInset
$limit     = [int]$G.fillLimit
$safety    = [double]$G.bandSafety

# ---------------------------------------------------------------------------
# derived numbers
# ---------------------------------------------------------------------------
$maxAbsX   = [int][Math]::Ceiling(($maxCols - 1) / 2.0 * $colSpacing) + $roomWall
$hallX     = $maxAbsX + [int]$G.hallMarginX
$entranceHalf = [int]$G.entranceHalf
if ($entranceHalf -lt 32 -or $entranceHalf -gt $hallX) { $entranceHalf = $hallX }
# The draft spawn is at z=0. Keep the south edge beyond it and clear old walls.
$southEdge = $rowSpacing - $roomWall + [int]$G.southPad
$bossZ     = ($rowSpacing * $rows * -1) - ($roomWall + $bossWall + $bossGap)
$northEdge = $bossZ - $bossWall - [int]$G.hallNorthMargin
$clearTop  = [int]$G.clearHeightTop
$clearBottom = [int]$G.clearHeightBottom
$clearSouth = [Math]::Max(($southEdge + [int]$G.clearSouthExtra), 34)

Write-Host ("geometry: rows={0} colSpacing={1} rowSpacing={2}" -f $rows, $colSpacing, $rowSpacing)
Write-Host ("hall: x +-{0}, z {1} .. {2}, bossZ={3}" -f $hallX, $southEdge, $northEdge, $bossZ)

function Write-Utf8 { param([string]$Path, [string]$Body)
    [System.IO.File]::WriteAllText($Path, $Body, (New-Object System.Text.UTF8Encoding($false)))
}
function New-Header { param([string]$Title, [string[]]$Notes)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("# AUTO-GENERATED by tools/gen-terrain.ps1 -- do not edit by hand.")
    [void]$sb.AppendLine("# Geometry comes from tools/geometry.json.")
    [void]$sb.AppendLine("# $Title")
    foreach ($n in $Notes) { [void]$sb.AppendLine("# $n") }
    [void]$sb.AppendLine("")
    return $sb
}
# split a z range into bands whose fill volume stays under the /fill limit
function Get-ZBands {
    param([int]$ZFrom, [int]$ZTo, [int]$Width, [int]$Height)
    $per = [int][Math]::Floor($limit * $safety / ($Width * $Height))
    if ($per -lt 1) { throw "band width too small" }
    $bands = @()
    $z = $ZFrom
    while ($z -gt $ZTo) {
        $end = [Math]::Max($ZTo, $z - $per + 1)
        $bands += ,@($z, $end)
        $z = $end - 1
    }
    return ,$bands
}

# ---------------------------------------------------------------------------
# 1) map/clear_floor  -- wipe this floor's volume in bands
# ---------------------------------------------------------------------------
$clearW = 2 * ($hallX + 1) + 1
$clearH = $clearTop - $clearBottom + 1
$sb = New-Header -Title "Clear this floor's whole volume (no rebuild)." -Notes @(
    "Runs at the floor base point. /fill is limited to $limit blocks per call,",
    "and an over-limit fill fails SILENTLY, so the range is split into Z bands.",
    "Clear through the south wall and below the floor, including hidden shop blocks."
)
foreach ($b in (Get-ZBands -ZFrom $clearSouth -ZTo $northEdge -Width $clearW -Height $clearH)) {
    [void]$sb.AppendLine(("fill ~{0} ~{1} ~{2} ~{3} ~{4} ~{5} minecraft:air" -f (-1 * ($hallX + 1)), $clearBottom, $b[0], ($hallX + 1), $clearTop, $b[1]))
}
Write-Utf8 (Join-Path $mapDir 'clear_floor.mcfunction') $sb.ToString()

# ---------------------------------------------------------------------------
# 2) map/build_hall
# ---------------------------------------------------------------------------
$sb = New-Header -Title "The floor's hall: solid rock, then only rooms and corridors are carved." -Notes @(
    "Rooms are cut out by map/room_shell / map/room_boss afterwards.",
    "No hall-wide ceiling any more: each room caps itself with barrier blocks.")
[void]$sb.AppendLine("function tspire:map/clear_floor")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# second floor layer under the walking surface")
foreach ($b in (Get-ZBands -ZFrom $southEdge -ZTo $northEdge -Width ($hallX * 2) -Height 1)) {
    [void]$sb.AppendLine(("fill ~{0} ~-2 ~{1} ~{2} ~-2 ~{3} minecraft:polished_andesite" -f (-1 * $hallX), $b[0], $hallX, $b[1]))
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# floor")
foreach ($b in (Get-ZBands -ZFrom $southEdge -ZTo $northEdge -Width ($hallX * 2) -Height 1)) {
    [void]$sb.AppendLine(("fill ~{0} ~-1 ~{1} ~{2} ~-1 ~{3} minecraft:polished_andesite" -f (-1 * $hallX), $b[0], $hallX, $b[1]))
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# solid rock body (y..y+4)")
foreach ($b in (Get-ZBands -ZFrom $southEdge -ZTo $northEdge -Width ($hallX * 2 + 1) -Height $roomH)) {
    [void]$sb.AppendLine(("fill ~{0} ~ ~{1} ~{2} ~{3} ~{4} minecraft:deepslate" -f (-1 * ($hallX + 1)), $b[0], ($hallX + 1), ($roomH - 1), $b[1]))
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# corridors between rows")
# entrance corridor
[void]$sb.AppendLine(("fill ~{0} ~ ~{1} ~{2} ~{3} ~{4} minecraft:air" -f (-1 * $entranceHalf), (-1 * (($rowSpacing * 1) - $roomWall - $cInset)), $entranceHalf, ($roomH - 1), $southEdge))
# south wall (v0.6.29): the spawn/draft spot sits inside the hall now, so close the
# south end with 2 blocks of rock instead of letting the player look into the void.
[void]$sb.AppendLine("# south wall (2 thick, just past the south edge)")
[void]$sb.AppendLine(("fill ~{0} ~ ~{1} ~{2} ~{3} ~{4} minecraft:deepslate" -f (-1 * ($hallX + 1)), ($southEdge + 2), ($hallX + 1), ($roomH - 1), ($southEdge + 1)))
for ($r = 1; $r -lt $rows; $r++) {
    $z1 = (-1 * ($rowSpacing * $r)) - $roomWall - $cInset
    $z2 = (-1 * ($rowSpacing * ($r + 1))) + $roomWall + $cInset
    [void]$sb.AppendLine(("fill ~{0} ~ ~{1} ~{2} ~{3} ~{4} minecraft:air" -f (-1 * $hallX), $z1, $hallX, ($roomH - 1), $z2))
}
# boss corridor
$bz1 = (-1 * ($rowSpacing * $rows)) - $roomWall - $cInset
$bz2 = $bossZ + $bossWall + $cInset
[void]$sb.AppendLine(("fill ~{0} ~ ~{1} ~{2} ~{3} ~{4} minecraft:air" -f (-1 * $hallX), $bz1, $hallX, ($roomH - 1), $bz2))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# corridor lights, embedded in the floor")
$lightZ = @($southEdge - 12)
for ($r = 1; $r -lt $rows; $r++) { $lightZ += ((-1 * ($rowSpacing * $r)) - [int]($rowSpacing / 2)) }
$lightZ += ($bossZ + $bossWall + 2)
foreach ($z in $lightZ) {
    [void]$sb.AppendLine(("fill ~-6 ~-1 ~{0} ~6 ~-1 ~{0} minecraft:sea_lantern" -f $z))
}
Write-Utf8 (Join-Path $mapDir 'build_hall.mcfunction') $sb.ToString()

# ---------------------------------------------------------------------------
# 3) map/room_shell  (normal room)
# ---------------------------------------------------------------------------
$door = @()
# The wall is $cInset blocks thick (corridorInset), so the doorway has to be
# carved all the way through it -- cutting only the inner block leaves the door
# opening into solid rock (that is exactly what blocked the entrances).
$door += ("fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:air" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1)))
$door += ("fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:air" -f $roomWall, ($roomWall + $cInset - 1))
$sb = New-Header -Title "A normal node room, carved out of the solid rock body." -Notes @(
    "Interior $((2*$roomHalf+1))x$((2*$roomHalf+1))x$roomH; the walls are just the rock that was not carved.",
    "Top is capped with barrier blocks so climbing spiders cannot leave.",
    "The centre floor block is LEFT ALONE: the map preset paints the node type there.")
[void]$sb.AppendLine(("fill ~-{0} ~ ~-{0} ~{0} ~{1} ~{0} minecraft:air" -f $roomHalf, ($roomH - 1)))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# barrier cap (per room, not the whole hall)")
[void]$sb.AppendLine(("fill ~-{0} ~{1} ~-{0} ~{0} ~{1} ~{0} minecraft:barrier" -f $roomWall, $barrierY))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# doors")
foreach ($d in $door) { [void]$sb.AppendLine($d) }
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# floor lamps: corners only (the centre block is the node type tile)")
foreach ($sx in @(-1, 1)) { foreach ($sz in @(-1, 1)) {
    [void]$sb.AppendLine(("setblock ~{0} ~-1 ~{1} minecraft:sea_lantern" -f ($sx * $roomHalf), ($sz * $roomHalf)))
} }
Write-Utf8 (Join-Path $mapDir 'room_shell.mcfunction') $sb.ToString()

# ---------------------------------------------------------------------------
# 4) map/room_boss
# ---------------------------------------------------------------------------
$sb = New-Header -Title "The boss arena: carved out of the same rock body." -Notes @(
    "Interior $((2*$bossHalf+1))x$((2*$bossHalf+1))x$roomH, one south door, four corner pillars.")
[void]$sb.AppendLine(("fill ~-{0} ~ ~-{0} ~{0} ~{1} ~{0} minecraft:air" -f $bossHalf, ($roomH - 1)))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# barrier cap")
[void]$sb.AppendLine(("fill ~-{0} ~{1} ~-{0} ~{0} ~{1} ~{0} minecraft:barrier" -f $bossWall, $barrierY))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# south door")
[void]$sb.AppendLine(("fill ~-2 ~ ~{0} ~2 ~2 ~{1} minecraft:air" -f $bossWall, ($bossWall + $cInset - 1)))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# corner pillars (cover)")
$p = $bossHalf - 6
[void]$sb.AppendLine(("fill ~-{0} ~ ~-{0} ~-{1} ~3 ~-{1} minecraft:deepslate" -f $p, ($p - 1)))
[void]$sb.AppendLine(("fill ~{1} ~ ~-{0} ~{0} ~3 ~-{1} minecraft:deepslate" -f $p, ($p - 1)))
[void]$sb.AppendLine(("fill ~-{0} ~ ~{1} ~-{1} ~3 ~{0} minecraft:deepslate" -f $p, ($p - 1)))
[void]$sb.AppendLine(("fill ~{1} ~ ~{1} ~{0} ~3 ~{0} minecraft:deepslate" -f $p, ($p - 1)))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("# floor lamps (centre left free for the node type tile)")
foreach ($sx in @(-1, 1)) { foreach ($sz in @(-1, 1)) {
    [void]$sb.AppendLine(("setblock ~{0} ~-1 ~{1} minecraft:sea_lantern" -f ($sx * $bossHalf), ($sz * $bossHalf)))
} }
Write-Utf8 (Join-Path $mapDir 'room_boss.mcfunction') $sb.ToString()

# ---------------------------------------------------------------------------
# 5) seal / unseal doors  (route enforcement is PHYSICAL)
# ---------------------------------------------------------------------------
foreach ($mode in @($sealBlock, 'air')) {
    $name = if ($mode -eq 'air') { 'unseal_doors' } else { 'seal_doors' }
    $sb = New-Header -Title "$name -- block/unblock the current node room's doors." -Notes @(
        "Executor = the node marker.",
        "v0.6.25: a PERMANENT seal uses the visible '$sealBlock' (geometry.json",
        "sealBlock) instead of barrier, so the player can see which rooms are off-limits.",
        "terrain/lock (temporary battle lock) still uses barrier on purpose.")
    [void]$sb.AppendLine(("fill ~-1 ~ ~{0} ~1 ~2 ~{1} {2}" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1)), $mode))
    [void]$sb.AppendLine(("fill ~-1 ~ ~{0} ~1 ~2 ~{1} {2}" -f $roomWall, ($roomWall + $cInset - 1), $mode))
    [void]$sb.AppendLine(("execute if entity @s[tag=tspire_type_boss] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} {2}" -f $bossWall, ($bossWall + $cInset - 1), $mode))
    [void]$sb.AppendLine(("execute if entity @s[tag=tspire_row15] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} {2}" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1)), $mode))
    [void]$sb.AppendLine(("execute if entity @s[tag=tspire_type_boss] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} {2}" -f $bossWall, ($bossWall + $cInset - 1), $mode))
    Write-Utf8 (Join-Path $mapDir "$name.mcfunction") $sb.ToString()
}

# ---------------------------------------------------------------------------
# 6) terrain/lock + unlock  (used by battle start/end)
# ---------------------------------------------------------------------------
$lock = New-Header -Title "Seal every door of the CURRENT node room at battle start." -Notes @()
[void]$lock.AppendLine(("execute at @e[tag=tspire_node_current,tag=!tspire_type_boss] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:barrier" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1))))
[void]$lock.AppendLine(("execute at @e[tag=tspire_node_current,tag=!tspire_type_boss] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:barrier" -f $roomWall, ($roomWall + $cInset - 1)))
[void]$lock.AppendLine(("execute at @e[tag=tspire_node_current,tag=tspire_type_boss] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:barrier" -f $bossWall, ($bossWall + $cInset - 1)))
[void]$lock.AppendLine(("execute at @e[tag=tspire_node_current,tag=tspire_row15] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} minecraft:barrier" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1))))
[void]$lock.AppendLine(("execute at @e[tag=tspire_node_current,tag=tspire_type_boss] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} minecraft:barrier" -f $bossWall, ($bossWall + $cInset - 1)))
Write-Utf8 (Join-Path $terDir 'lock.mcfunction') $lock.ToString()

$unlock = New-Header -Title "Open every door of the CURRENT node room at battle end." -Notes @()
[void]$unlock.AppendLine(("execute at @e[tag=tspire_node_current] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:air" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1))))
[void]$unlock.AppendLine(("execute at @e[tag=tspire_node_current] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:air" -f $roomWall, ($roomWall + $cInset - 1)))
[void]$unlock.AppendLine(("execute at @e[tag=tspire_node_current] run fill ~-1 ~ ~{0} ~1 ~2 ~{1} minecraft:air" -f $bossWall, ($bossWall + $cInset - 1)))
[void]$unlock.AppendLine(("execute at @e[tag=tspire_node_current,tag=tspire_row15] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} minecraft:air" -f (-1 * $roomWall), (-1 * ($roomWall + $cInset - 1))))
[void]$unlock.AppendLine(("execute at @e[tag=tspire_node_current,tag=tspire_type_boss] run fill ~-2 ~ ~{0} ~2 ~2 ~{1} minecraft:air" -f $bossWall, ($bossWall + $cInset - 1)))
Write-Utf8 (Join-Path $terDir 'unlock.mcfunction') $unlock.ToString()

# ---------------------------------------------------------------------------
# 7) forceload range (must cover the whole hall + boss)
# ---------------------------------------------------------------------------
$flx1 = [int][Math]::Floor((-$hallX - 1) / 16.0) * 16
$flx2 = [int][Math]::Ceiling(($hallX + 1) / 16.0) * 16
$flz1 = [int][Math]::Ceiling($southEdge / 16.0) * 16
$flz2 = [int][Math]::Floor($northEdge / 16.0) * 16
$chunks = ([int](($flx2 - $flx1) / 16) + 1) * ([int](($flz1 - $flz2) / 16) + 1)
Write-Host ("forceload add {0} {1} {2} {3}   ({4} chunks)" -f $flx1, $flz2, $flx2, $flz1, $chunks)
Write-Utf8 (Join-Path $PSScriptRoot 'geometry-forceload.txt') ("{0} {1} {2} {3}" -f $flx1, $flz2, $flx2, $flz1)

Write-Host "done: terrain functions generated"

# Route unlocking is generated by gen-runtime-map.js.
& node (Join-Path $PSScriptRoot 'gen-map-stages.js')
if ($LASTEXITCODE -ne 0) { throw 'gen-map-stages.js failed' }
