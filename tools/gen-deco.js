// ---------------------------------------------------------------------------
// minimal NBT reader (big-endian, no external deps)
// ---------------------------------------------------------------------------
function parseNBT(buf, start) {
  let off = start === undefined ? 0 : start;
  const rd = (n) => {
    const v = buf.subarray(off, off + n);
    off += n;
    return v;
  };
  const rU8 = () => buf[off++];
  const rI8 = () => { const v = buf.readInt8(off); off += 1; return v; };
  const rI16 = () => { const v = buf.readInt16BE(off); off += 2; return v; };
  const rI32 = () => { const v = buf.readInt32BE(off); off += 4; return v; };
  const rI64 = () => { const v = buf.readBigInt64BE(off); off += 8; return v; };
  const rF32 = () => { const v = buf.readFloatBE(off); off += 4; return v; };
  const rF64 = () => { const v = buf.readDoubleBE(off); off += 8; return v; };
  const rStr = () => { const n = buf.readUInt16BE(off); off += 2; const s = buf.toString('utf8', off, off + n); off += n; return s; };

  function payload(type) {
    switch (type) {
      case 1: return rI8();
      case 2: return rI16();
      case 3: return rI32();
      case 4: return rI64();
      case 5: return rF32();
      case 6: return rF64();
      case 7: { const n = rI32(); return rd(n); }
      case 8: return rStr();
      case 9: {
        const itemType = rU8();
        const n = rI32();
        const out = [];
        for (let i = 0; i < n; i++) out.push(payload(itemType));
        return out;
      }
      case 10: {
        const out = {};
        for (;;) {
          const t = rU8();
          if (t === 0) break;
          const name = rStr();
          out[name] = payload(t);
        }
        return out;
      }
      case 11: { const n = rI32(); const out = []; for (let i = 0; i < n; i++) out.push(rI32()); return out; }
      case 12: { const n = rI32(); const out = []; for (let i = 0; i < n; i++) out.push(rI64()); return out; }
      default: throw new Error('unknown NBT tag type ' + type + ' at ' + off);
    }
  }

  const rootType = rU8();
  if (rootType !== 10) throw new Error('root tag is not a compound (' + rootType + ')');
  rStr(); // root name, usually empty
  return { value: payload(10), offset: off };
}

// ---------------------------------------------------------------------------
// typed NBT reader + SNBT writer (used for BLOCK ENTITIES only)
// ---------------------------------------------------------------------------
// Block states alone are not enough for some of the player's rooms:
//   * minecraft:hanging_sign -- the text lives in the block entity (front_text/back_text)
//   * tconstruct:smeltery / drains / tanks / faucets -- the multiblock links
//     (masterOffset / masterBlock / multiblock) and the fluid tanks live in the BEs
//   * chests -- their contents
// So for every block entity inside the box we also emit a `setblock ... <state> {SNBT}`.
function parseTyped(buf, start, type) {
  let off = start;
  const t = type === undefined ? buf[off++] : type;
  const rI8 = () => buf.readInt8(off++);
  const rU8 = () => buf[off++];
  const rI16 = () => { const v = buf.readInt16BE(off); off += 2; return v; };
  const rI32 = () => { const v = buf.readInt32BE(off); off += 4; return v; };
  const rI64 = () => { const v = buf.readBigInt64BE(off); off += 8; return v; };
  const rF32 = () => { const v = buf.readFloatBE(off); off += 4; return v; };
  const rF64 = () => { const v = buf.readDoubleBE(off); off += 8; return v; };
  const rStr = () => { const n = buf.readUInt16BE(off); off += 2; const s = buf.toString('utf8', off, off + n); off += n; return s; };

  function read(ty) {
    switch (ty) {
      case 1: return { t: 'byte', v: rI8() };
      case 2: return { t: 'short', v: rI16() };
      case 3: return { t: 'int', v: rI32() };
      case 4: return { t: 'long', v: rI64() };
      case 5: return { t: 'float', v: rF32() };
      case 6: return { t: 'double', v: rF64() };
      case 7: { const n = rI32(); const v = []; for (let i = 0; i < n; i++) v.push(rI8()); return { t: 'byteArray', v }; }
      case 8: return { t: 'string', v: rStr() };
      case 9: {
        const itemType = rU8();
        const n = rI32();
        const v = [];
        for (let i = 0; i < n; i++) v.push(read(itemType));
        return { t: 'list', v };
      }
      case 10: {
        const v = {};
        for (;;) {
          const kt = rU8();
          if (kt === 0) break;
          const k = rStr();
          v[k] = read(kt);
        }
        return { t: 'compound', v };
      }
      case 11: { const n = rI32(); const v = []; for (let i = 0; i < n; i++) v.push(rI32()); return { t: 'intArray', v }; }
      case 12: { const n = rI32(); const v = []; for (let i = 0; i < n; i++) v.push(rI64()); return { t: 'longArray', v }; }
      default: throw new Error('unknown NBT tag type ' + ty + ' at ' + off);
    }
  }
  const node = read(t);
  return { node, end: off };
}

function snbtKey(k) { return /^[A-Za-z0-9_.+-]+$/.test(k) ? k : '"' + k.replace(/"/g, '\\"') + '"'; }

function toSnbt(n) {
  switch (n.t) {
    case 'byte': return n.v + 'b';
    case 'short': return n.v + 's';
    case 'int': return String(n.v);
    case 'long': return n.v + 'L';
    case 'float': return numLit(n.v) + 'f';
    case 'double': return numLit(n.v) + 'd';
    case 'string': return '"' + String(n.v).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
    case 'byteArray': return '[B;' + n.v.map((x) => x + 'b').join(',') + ']';
    case 'intArray': return '[I;' + n.v.map(String).join(',') + ']';
    case 'longArray': return '[L;' + n.v.map((x) => x + 'L').join(',') + ']';
    case 'list': return '[' + n.v.map(toSnbt).join(',') + ']';
    case 'compound': return '{' + Object.entries(n.v).map(([k, v]) => snbtKey(k) + ':' + toSnbt(v)).join(',') + '}';
    default: throw new Error('toSnbt: unknown ' + n.t);
  }
}
function numLit(v) { const s = Number(v).toString(); return /[.eE]/.test(s) ? s : s + '.0'; }

// walk the root compound of a chunk and pull out `block_entities` as typed nodes
function blockEntitiesTyped(raw) {
  let off = 0;
  const rootType = raw[off++];
  if (rootType !== 10) return [];
  const nl = raw.readUInt16BE(off); off += 2 + nl;      // root name
  const out = [];
  for (;;) {
    const kt = raw[off++];
    if (kt === 0) break;
    const kl = raw.readUInt16BE(off); off += 2;
    const key = raw.toString('utf8', off, off + kl); off += kl;
    const res = parseTyped(raw, off, kt);
    off = res.end;
    if (key === 'block_entities' && kt === 9) {
      for (const item of res.node.v) {
        if (item.t !== 'compound') continue;
        const g = (k) => (item.v[k] ? item.v[k].v : undefined);
        out.push({ x: g('x'), y: g('y'), z: g('z'), id: g('id'), node: item });
      }
    }
  }
  return out;
}

// keys that must not be written back (command sets them, or they are runtime-only)
const BE_SKIP_KEYS = ['id', 'x', 'y', 'z', 'keepPacked', 'last_vibration_frequency', 'listener'];

// walk the root compound of a chunk and pull out `entities` as typed nodes.
// In 1.20.1 the chunk NBT carries `entities` next to `block_entities`; each entry has a
// double `Pos` list, so we keep the FRACTIONAL part (armour stands usually sit on .5).
function entitiesTyped(raw) {
  let off = 0;
  const rootType = raw[off++];
  if (rootType !== 10) return [];
  const nl = raw.readUInt16BE(off); off += 2 + nl;      // root name
  const out = [];
  for (;;) {
    const kt = raw[off++];
    if (kt === 0) break;
    const kl = raw.readUInt16BE(off); off += 2;
    const key = raw.toString('utf8', off, off + kl); off += kl;
    const res = parseTyped(raw, off, kt);
    off = res.end;
    if (key === 'Entities' && kt === 9) {
      for (const item of res.node.v) {
        if (item.t !== 'compound') continue;
        const g = (k) => (item.v[k] ? item.v[k].v : undefined);
        // NOTE: g() already unwraps `.v`, so `Pos` comes back as the raw array of doubles
        const pos = g('Pos');
        if (!Array.isArray(pos) || pos.length < 3) continue;
        const num = (d) => (d && typeof d === 'object' ? d.v : d);
        out.push({ id: g('id'), fx: num(pos[0]), fy: num(pos[1]), fz: num(pos[2]), node: item });
      }
    }
  }
  return out;
}

// entity SNBT: like beToSnbt, but `overrides` win over whatever the source had
function entToSnbt(node, extraSkip, overrides) {
  const skip = BE_SKIP_KEYS.concat(ENTITY_SKIP_KEYS).concat(extraSkip || []);
  const parts = [];
  for (const [k, v] of Object.entries(node.v)) {
    if (skip.includes(k)) continue;
    if (overrides && Object.prototype.hasOwnProperty.call(overrides, k)) continue;
    parts.push(snbtKey(k) + ':' + toSnbt(v));
  }
  for (const [k, v] of Object.entries(overrides || {})) parts.push(snbtKey(k) + ':' + v);
  return '{' + parts.join(',') + '}';
}


function beToSnbt(node, extraSkip) {
  const skip = BE_SKIP_KEYS.concat(extraSkip || []);
  const parts = [];
  for (const [k, v] of Object.entries(node.v)) {
    if (skip.includes(k)) continue;
    parts.push(snbtKey(k) + ':' + toSnbt(v));
  }
  return '{' + parts.join(',') + '}';
}


const chunkCache = new Map();
const chunkRawCache = new Map();
// 1.17+ stores entities in a SEPARATE folder (`<dimension>/entities/r.x.z.mca`) whose chunk
// root carries an `Entities` list instead of blocks. Read it with the same .mca framing.
const entityRawCache = new Map();
function loadEntityChunkRaw(cx, cz) {
  const key = cx + ',' + cz;
  if (entityRawCache.has(key)) return entityRawCache.get(key);
  const p = path.join(ENTITY_DIR, 'r.' + (cx >> 5) + '.' + (cz >> 5) + '.mca');
  let raw = null;
  if (fs.existsSync(p)) {
    const buf = fs.readFileSync(p);
    const li = 4 * ((cx & 31) + (cz & 31) * 32);
    const off = buf.readUIntBE(li, 3);
    const cnt = buf[li + 3];
    if (off && cnt) {
      const rec = off * 4096;
      const len = buf.readUInt32BE(rec);
      const comp = buf[rec + 4];
      const data = buf.subarray(rec + 5, rec + 4 + len);
      if (comp === 1) raw = zlib.gunzipSync(data);
      else if (comp === 2) raw = zlib.inflateSync(data);
      else if (comp === 3) raw = data;
    }
  }
  entityRawCache.set(key, raw);
  return raw;
}

function loadChunkRaw(cx, cz) {
  const key = cx + ',' + cz;
  if (chunkRawCache.has(key)) return chunkRawCache.get(key);
  const p = path.join(REGION_DIR, 'r.' + (cx >> 5) + '.' + (cz >> 5) + '.mca');
  let raw = null;
  if (fs.existsSync(p)) {
    const buf = fs.readFileSync(p);
    const li = 4 * ((cx & 31) + (cz & 31) * 32);
    const off = buf.readUIntBE(li, 3);
    const cnt = buf[li + 3];
    if (off && cnt) {
      const rec = off * 4096;
      const len = buf.readUInt32BE(rec);
      const comp = buf[rec + 4];
      const data = buf.subarray(rec + 5, rec + 4 + len);
      if (comp === 1) raw = zlib.gunzipSync(data);
      else if (comp === 2) raw = zlib.inflateSync(data);
      else if (comp === 3) raw = data;
      else throw new Error('unsupported chunk compression ' + comp + ' in ' + p);
    }
  }
  chunkRawCache.set(key, raw);
  return raw;
}

function loadChunk(cx, cz) {
  const key = cx + ',' + cz;
  if (chunkCache.has(key)) return chunkCache.get(key);
  const raw = loadChunkRaw(cx, cz);
  const chunk = raw ? parseNBT(raw).value : null;
  chunkCache.set(key, chunk);
  return chunk;
}

function stateString(paletteEntry) {
  const name = paletteEntry.Name;
  const props = paletteEntry.Properties;
  if (!props) return name;
  const keys = Object.keys(props).sort();
  return name + '[' + keys.map((k) => k + '=' + props[k]).join(',') + ']';
}

function ceilLog2(n) { let b = 0; while ((1 << b) < n) b++; return b; }

// read a box of block states: returns { blocks: Map("x,y,z" -> state), missing: [chunks] }
function readBox(minX, minY, minZ, maxX, maxY, maxZ) {
  const blocks = new Map();
  const missing = [];
  const blockEntities = [];
  const entities = [];
  for (let cx = minX >> 4; cx <= (maxX >> 4); cx++) {
    for (let cz = minZ >> 4; cz <= (maxZ >> 4); cz++) {
      const chunk = loadChunk(cx, cz);
      if (!chunk) { missing.push(cx + ',' + cz); continue; }
      // sample only the part of the box that lives inside THIS chunk
      const x0 = Math.max(minX, cx * 16), x1 = Math.min(maxX, cx * 16 + 15);
      const z0 = Math.max(minZ, cz * 16), z1 = Math.min(maxZ, cz * 16 + 15);
      // block entities: keep the TYPED node so we can write exact SNBT back
      const rawChunk = loadChunkRaw(cx, cz);
      for (const be of (rawChunk ? blockEntitiesTyped(rawChunk) : [])) {
        if (be.x >= minX && be.x <= maxX && be.y >= minY && be.y <= maxY && be.z >= minZ && be.z <= maxZ) {
          blockEntities.push(be);
        }
      }
      // entities (armour stands / item frames): decoration props that are NOT blocks.
      // They live in the dimension's `entities` folder, not in the block region.
      const rawEnt = loadEntityChunkRaw(cx, cz);
      for (const en of (rawEnt ? entitiesTyped(rawEnt) : [])) {
        if (en.fx >= minX && en.fx <= maxX + 1 && en.fy >= minY && en.fy <= maxY && en.fz >= minZ && en.fz <= maxZ + 1) {   // v0.7.38: y 上限不用 maxY+1（那是屏障层，summon 进去会被顶到屏障上方）
          entities.push(en);
        }
      }
      for (const sec of (chunk.sections || [])) {
        const sy = sec.Y;
        const y0 = sy * 16;
        const y1 = y0 + 15;
        if (y1 < minY || y0 > maxY) continue;
        const bs = sec.block_states;
        const palette = bs && bs.palette ? bs.palette.map(stateString) : ['minecraft:air'];
        const data = bs && bs.data ? bs.data : null;
        const bits = Math.max(4, ceilLog2(palette.length));
        const perLong = Math.floor(64 / bits);
        const mask = (1n << BigInt(bits)) - 1n;
        for (let y = Math.max(y0, minY); y <= Math.min(y1, maxY); y++) {
          for (let z = z0; z <= z1; z++) {
            for (let x = x0; x <= x1; x++) {
              let pi = 0;
              if (data) {
                const idx = ((y - y0) * 16 + (z & 15)) * 16 + (x & 15);
                const li = Math.floor(idx / perLong);
                const sh = BigInt((idx % perLong) * bits);
                pi = Number((data[li] >> sh) & mask);
              }
              if (global.DECO_DEBUG && x === 70 && y === 56 && z === -7) {
                console.log('    [dbg] chunk ' + (x >> 4) + ',' + (z >> 4) + ' secY=' + sy +
                  ' palette=' + palette.length + ' bits=' + bits + ' perLong=' + perLong +
                  ' hasData=' + !!data + ' idx=' + (((y - y0) * 16 + (z & 15)) * 16 + (x & 15)) +
                  ' pi=' + pi + ' -> ' + palette[pi]);
              }
              blocks.set(x + ',' + y + ',' + z, palette[pi] || 'minecraft:air');
            }
          }
        }
        // sections without block_states mean "all air" -- nothing stored, callers default to air
      }
    }
  }
  return { blocks, missing, blockEntities, entities };
}

// ---------------------------------------------------------------------------
// command emission: run-length along x per row, then merge identical rows along z
// ---------------------------------------------------------------------------
function emitCommands(blocks, anchor, r) {
  const [ax, ay, az] = anchor; // anchor = (centre x, floor-walk y, centre z)
  const yMin = -1, yMax = 4;   // 6 layers: floor(-1) + interior(0..4) = y 56..61（**不含 y62 屏障层**，v0.7.36 改回）
  const out = [];
  for (let ry = yMin; ry <= yMax; ry++) {
    let open = null; // { x1, x2, zStart, zEnd, state }
    let prevRuns = null;
    for (let rz = -r; rz <= r; rz++) {
      const runs = [];
      let cur = null;
      for (let rx = -r; rx <= r; rx++) {
        const st = blocks.get((ax + rx) + ',' + (ay + ry) + ',' + (az + rz)) || 'minecraft:air';
        if (cur && cur.state === st) { cur.x2 = rx; } else { cur = { x1: rx, x2: rx, state: st }; runs.push(cur); }
      }
      const same = prevRuns && prevRuns.length === runs.length &&
        prevRuns.every((p, i) => p.state === runs[i].state && p.x1 === runs[i].x1 && p.x2 === runs[i].x2);
      if (same) {
        for (let i = 0; i < runs.length; i++) open[i].zEnd = rz;
      } else {
        if (open) for (const f of open) out.push(fillLine(f, ry));
        open = runs.map((rn) => ({ x1: rn.x1, x2: rn.x2, zStart: rz, zEnd: rz, state: rn.state }));
      }
      prevRuns = runs;
    }
    if (open) for (const f of open) out.push(fillLine(f, ry));
  }
  return out;
}

function fillLine(f, ry) {
  return 'fill ~' + f.x1 + ' ~' + ry + ' ~' + f.zStart + ' ~' + f.x2 + ' ~' + ry + ' ~' + f.zEnd + ' ' + f.state;
}

// ---------------------------------------------------------------------------
// combat-integration check: the mob spawn cells and the straggler teleport cell
// (from run/battle_start + mobs/groups/floor1_*: squads sit at rz -3 / -5, and
//  battle_start pulls late players to the room centre +2 z)
// ---------------------------------------------------------------------------
const MOB_CELLS = [[-6, -3], [-3, -3], [0, -3], [3, -3], [6, -3], [-6, -5], [-3, -5], [0, -5]];
const PLAYER_CELL = [0, 2];
// states that do not block a spawn / teleport (a mob can stand inside them)
const PASSABLE = /^minecraft:(air|cave_air|void_air|grass|tall_grass|fern|large_fern|dandelion|poppy|allium|blue_orchid|oxeye_daisy|cornflower|lily_of_the_valley|pink_petals|brown_mushroom|red_mushroom|moss_carpet|dead_bush|azalea|flowering_azalea|torch|redstone_torch|lantern|soul_lantern|vine|snow|water)$|_(carpet|petals|torch|lantern|button|lever|sign|banner)$/;
// Tinkers' plants are the same class of block as vanilla tall grass: no collision, and
// spawning inside them is normal vanilla behaviour. (The *_slime_grass SURFACE blocks are
// full cubes and must NOT be listed here.)
const PASSABLE_TC = /^tconstruct:.*(_slime_tall_grass|_slime_fern|_slime_sapling|_slime_sprout)$/;
// Blocks that really hurt / trap a mob standing in them -> these DO get cleared.
const HAZARD = /^minecraft:(fire|soul_fire|campfire|soul_campfire|lava|magma_block|cactus|sweet_berry_bush|wither_rose|powder_snow|pointed_dripstone)$/;

function spawnCheck(blocks, anchor) {
  const [ax, ay, az] = anchor;
  const bad = [];
  for (const [rx, rz] of MOB_CELLS.concat([PLAYER_CELL])) {
    for (const ry of [0, 1]) {
      const st = blocks.get((ax + rx) + ',' + (ay + ry) + ',' + (az + rz)) || 'minecraft:air';
      const short = st.replace(/\[.*$/, '');
      if (PASSABLE.test(short) || PASSABLE_TC.test(short)) continue;
      // "hard" = hurts/traps a mob (fire, campfire, lava ...) -> clear feet+head.
      // "soft" = everything else (slab, log, fence, leaves, stone ...): the game pushes a
      // summoned mob out of it, so we only REPORT it and leave the player's build alone.
      bad.push({ rx, rz, ry, st, hard: HAZARD.test(short) });
    }
  }
  return bad;
}

// replay a command list into a voxel map and compare with the source capture
function verify(cmds, blocks, anchor, r) {
  const [ax, ay, az] = anchor;
  const got = new Map();
  for (const line of cmds) {
    const m = line.match(/^fill (~-?\d*) (~-?\d*) (~-?\d*) (~-?\d*) (~-?\d*) (~-?\d*) (.+)$/);
    if (!m) continue;
    const v = m.slice(1, 7).map((s) => Number(s.slice(1) || '0'));
    const state = m[7].trim();
    const [x1, y1, z1, x2, y2, z2] = v;
    for (let x = Math.min(x1, x2); x <= Math.max(x1, x2); x++) {
      for (let y = Math.min(y1, y2); y <= Math.max(y1, y2); y++) {
        for (let z = Math.min(z1, z2); z <= Math.max(z1, z2); z++) {
          got.set(x + ',' + y + ',' + z, state);
        }
      }
    }
  }
  const bad = [];
  for (let ry = -1; ry <= 4; ry++) {
    for (let rz = -7; rz <= 7; rz++) {
      for (let rx = -7; rx <= 7; rx++) {
        const key = (ax + rx) + ',' + (ay + ry) + ',' + (az + rz);
        const want = blocks.get(key) || 'minecraft:air';
        const have = got.get(rx + ',' + ry + ',' + rz) || 'minecraft:air';
        if (want !== have) bad.push('(' + rx + ',' + ry + ',' + rz + ') want ' + want + ' got ' + have);
      }
    }
  }
  return bad;
}

