// gen-signs.js -- 从已生成的 deco/*.mcfunction 里抽出**告示牌**，写成 deco/<房间>_signs.mcfunction。
//
// 为什么需要它：
//   房间装饰是"建一次"的（map/enter_artisan 用 tspire_node_built 把门）。
//   于是**后加**的告示牌在"已经建好的房间里"永远不会出现 —— 玩家实测就是
//   "告示牌文字没有正常写入"。
//   解决思路与 v0.7.21 的燃料罐完全一样：把这一小段放到闸门**外面**、每次进房重写。
//
// 【v0.7.43 关键改动：setblock → data merge block】
//   实测（玩家 12:46 诊断）：函数跑了 4 次、牌子是墙牌、支撑也在，
//   但 `setblock ~-6 ~1 ~0 minecraft:oak_wall_sign[facing=east,waterlogged=false]{front_text:…}`
//   **执行了却写不进文字**（正/背面都还是空串）。
//   而同一间房里的 `deco/artisan_fuel` 用 `data merge block` 补燃料罐**是成功的**。
//   所以这里改成同样可靠的写法：方块**已经由 deco/<房间> 铺好**，
//   `_signs` 只负责把文字 merge 进去：
//       data merge block <x> <y> <z> {front_text:{…},back_text:{…},is_waxed:0b}
//   （data merge 是在已有方块实体上原地合并，不需要重复放置方块。）
//
// 用法：node tools/gen-signs.js          （每次 gen-deco.js 之后跑一次）
const fs = require('fs');
const path = require('path');

const DECO = path.join(__dirname, '..', 'src', 'main', 'resources', 'data', 'tspire', 'functions', 'deco');
const files = fs.readdirSync(DECO).filter((f) => f.endsWith('.mcfunction') && !f.endsWith('_signs.mcfunction'));

let made = 0, total = 0;
for (const f of files) {
  const name = f.replace(/\.mcfunction$/, '');
  const lines = fs.readFileSync(path.join(DECO, f), 'utf8').split(/\r?\n/);
  const outLines = [];
  for (const l of lines) {
    if (!/^setblock\s/.test(l) || !/sign/.test(l)) continue;
    // setblock <x> <y> <z> <block>[state]{NBT}   ->   data merge block <x> <y> <z> {NBT}
    const m = l.match(/^setblock\s+(~\S+)\s+(~\S+)\s+(~\S+)\s+\S+?(\{.*\})\s*$/);
    if (!m) continue;
    outLines.push('data merge block ' + m[1] + ' ' + m[2] + ' ' + m[3] + ' ' + m[4]);
  }
  if (!outLines.length) continue;
  const out = [
    '# AUTO-GENERATED by tools/gen-signs.js -- do not edit by hand.',
    '# 「' + name + '」的**告示牌文字**（从 ' + name + '.mcfunction 里抽出来）。',
    '# 调用方在**每次进房**时跑一遍，这样"后加的告示牌"在老房间里也能出现。',
    '# v0.7.43：改用 `data merge block`（原地合并进已有方块实体）——',
    '#   实测 `setblock …{front_text:…}` 在本环境**执行了但写不进文字**，而同一间房的',
    '#   deco/artisan_fuel 用 data merge 补燃料罐是成功的，所以这里换同样可靠的写法。',
    '# 只含告示牌 —— 冶炼炉/箱子的 NBT 重写会把玩家放进去的东西刷掉，绝不能放进来。',
    '# 执行前提：at 当前节点标记（房间中心、地板行走层）；方块必须已经铺好（deco/<房间> 负责）。',
    '',
  ].concat(outLines, ['']);
  fs.writeFileSync(path.join(DECO, name + '_signs.mcfunction'), out.join('\n'), 'utf8');
  made++; total += outLines.length;
}
console.log('signs functions written: ' + made + '  (total ' + total + ' merge command(s))');
